export type RomaniaJudet = (typeof ROMANIA_JUDETE)[number];

function judetKey(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .replace(/[^a-z0-9]+/g, "");
}

const LOOKUP = new Map(
  ROMANIA_JUDETE.map((name) => [judetKey(name), name] as const),
);

export function resolveJudet(input: string): RomaniaJudet | null {
  return LOOKUP.get(judetKey(input)) ?? null;
}

export function isValidJudet(input: string): boolean {
  return resolveJudet(input) !== null;
}