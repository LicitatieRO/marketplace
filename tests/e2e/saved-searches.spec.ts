import { test, expect } from '@playwright/test';
test.skip(process.env.E2E_BACKEND !== '1', 'Requires disposable local Auth/database');
test('verified buyer saves private filters, gets a queued change alert and deletes search', async ({ page, request }, testInfo) => {
  test.skip(!process.env.E2E_OWNER_EMAIL || !process.env.E2E_BUYER_EMAIL || !process.env.E2E_PASSWORD, 'Local integration credentials required');
  const english = testInfo.project.name === 'mobile';
  await page.addInitScript((english) => {
    localStorage.setItem('licitatiero-language', english ? 'en' : 'ro');
    localStorage.setItem('licitatiero-theme', english ? 'dark' : 'light');
    localStorage.setItem('licitatiero-optional-content', 'rejected');
  }, english);
  const headers = { Origin: String(testInfo.project.use.baseURL) };
  expect((await request.post('/api/auth', { headers, data: { action: 'login', email: process.env.E2E_OWNER_EMAIL, password: process.env.E2E_PASSWORD } })).status()).toBe(200);
  const suffix = `${testInfo.project.name}-${crypto.randomUUID().slice(0, 8)}`;
  const area = `Search area ${suffix}`, name = `Saved ${suffix}`;
  const propertyInput = { p_title: `Saved search property ${suffix}`, p_description: 'Disposable browser fixture for saved search alerts.', p_neighborhood: area, p_exact_address: 'Private browser search fixture address', p_property_type: 'apartment', p_area_sqm: 70, p_rooms: 3, p_floor: 2, p_built_year: 2020, p_sale_price_minor: 100000, p_rent_price_minor: null, p_image_urls: [] };
  const created = await request.post('/api/marketplace', { headers, data: { action: 'create_property', payload: propertyInput } });
  expect(created.status()).toBe(200);
  const property = (await created.json()).data;
  await page.goto(`/saved-searches?transaction_type=sale&neighborhood=${encodeURIComponent(area)}&max_price=2000&min_rooms=2`);
  const signIn = page.getByRole('main').getByRole('link', { name: english ? 'Sign in' : 'Intră în cont', exact: true });
  await expect(signIn).toHaveAttribute('href', /next=%2Fsaved-searches/);
  await signIn.click();
  await page.getByLabel(english ? 'Email address' : 'Adresa de email').fill(process.env.E2E_BUYER_EMAIL!);
  await page.getByLabel(english ? 'Password' : 'Parola', { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button', { name: english ? 'Sign in' : 'Intră în cont', exact: true }).click();
  await expect(page).toHaveURL(/\/saved-searches/);
  expect(new URL(page.url()).searchParams.get('neighborhood')).toBe(area);
  await expect(page.getByRole('heading', { name: english ? 'Saved searches' : 'Căutări salvate', level: 1 })).toBeVisible();
  await page.getByLabel(english ? 'Search name' : 'Numele căutării').fill(name);
  await expect(page.getByLabel(english ? 'Maximum price, EUR' : 'Preț maxim, EUR')).toHaveValue('2000');
  const save = page.getByRole('button', { name: english ? 'Save search' : 'Salvează căutarea', exact: true });
  await expect(save).toBeEnabled();
  await save.click();
  await expect(page.getByText(english ? 'Search saved.' : 'Căutare salvată.', { exact: true })).toBeVisible();
  const rows = (await (await page.request.get('/api/saved-searches')).json()).data;
  const search = rows.find((item: { name: string }) => item.name === name);
  expect(Boolean(search)).toBe(true);
  const card = page.getByTestId(`saved-search-${search.id}`);
  await expect(card).toContainText(area);
  await page.reload();
  await expect(card).toContainText(name);
  const foreign = (await (await request.get('/api/saved-searches')).json()).data;
  expect(foreign.some((item: { id: string }) => item.id === search.id)).toBe(false);
  const deniedDelete = await request.delete('/api/saved-searches', { headers, data: { id: search.id } });
  expect((await deniedDelete.json()).data.deleted).toBe(false);
  const changed = await request.post('/api/marketplace', { headers, data: { action: 'update_property', payload: { ...propertyInput, p_property_id: property.id, p_sale_price_minor: 110000 } } });
  expect(changed.status()).toBe(200);
  const after = (await (await page.request.get('/api/saved-searches')).json()).data.find((item: { id: string }) => item.id === search.id);
  expect(Boolean(after.last_notified_at)).toBe(true);
  await page.getByRole('button', { name: english ? 'Refresh' : 'Actualizează', exact: true }).click();
  await expect(card).toContainText(english ? 'Last alert queued:' : 'Ultima alertă pusă în coadă:');
  await card.getByRole('button', { name: english ? 'Delete search' : 'Șterge căutarea' }).click();
  await expect(card).toHaveCount(0);
  const remaining = (await (await page.request.get('/api/saved-searches')).json()).data;
  expect(remaining.some((item: { id: string }) => item.id === search.id)).toBe(false);
});
